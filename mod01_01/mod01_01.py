def sumComplex(num1,num2):
    #Complete the function by returning num1 + num2
    return num1 + num2
    
# function that takes two well-formed complex numbers as its inputs and outputs their product as a well-formed complex number.
def productComplex(num1,num2):
    #Complete the function by returning num1 * num2
    return num1 * num2
    
